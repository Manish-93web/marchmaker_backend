import { writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { NOTIFICATION_SPECS, resolvePrefs } from '@marchmaker/shared';
import { templateFor } from '@marchmaker/email';

const NAMES = new Map<unknown, string>();

/** Builds the event x channel x can-disable x template table from the live catalog, so the doc cannot drift from the code. */
export function notificationMatrix(): string {
  const prefs = resolvePrefs({});
  const yes = (b: boolean) => (b ? 'yes' : 'no');
  const rows = Object.entries(NOTIFICATION_SPECS).map(([event, spec]) => {
    const all = ['in_app', 'email', 'push', 'whatsapp'] as const;
    const channels = (spec.only ?? all).map((c) => (c === 'in_app' ? 'in-app' : c === 'whatsapp' ? 'WhatsApp' : c));
    const defaults = all.filter((c) => (!spec.only || spec.only.includes(c)) && prefs.channels[spec.category][c]).map((c) => (c === 'in_app' ? 'in-app' : c === 'whatsapp' ? 'WhatsApp' : c));
    const emailTemplate = !spec.only || spec.only.includes('email') ? (templateFor(event)?.name ?? NAMES.get(event) ?? 'Notice') : '-';
    const wa = !spec.only || spec.only.includes('whatsapp') ? 'mm_notification' : '-';
    return `| \`${event}\` | ${spec.category} | ${channels.join(', ')} | ${defaults.join(', ') || '-'} | ${yes(!spec.critical)} | ${emailTemplate} | ${wa} |`;
  });
  return [
    '| Event | Category | Channels it can use | On by default | Member can switch off | Email template | WhatsApp template |',
    '|---|---|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

const START = '<!-- matrix:start -->';
const END = '<!-- matrix:end -->';

/** Rewrites the table between the markers in docs/NOTIFICATIONS.md. */
if (process.argv[1]?.includes('notificationMatrix')) {
  const file = path.resolve(process.cwd(), '../../docs/NOTIFICATIONS.md');
  const doc = readFileSync(file, 'utf8');
  const next = doc.includes(START) ? doc.replace(new RegExp(`${START}[\s\S]*${END}`), `${START}\n${notificationMatrix()}\n${END}`) : `${doc}\n## Event matrix\n\nGenerated by \`pnpm --filter @marchmaker/api docs:notifications\`; a test fails if it is out of date. "Member can switch off: no" means the message is critical and always reaches in-app and email.\n\n${START}\n${notificationMatrix()}\n${END}\n`;
  writeFileSync(file, next);
}
